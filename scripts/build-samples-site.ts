// Builds build/samples-site: the sample apps plus the /_deft/v1 runtime, for the samples Worker (wrangler.toml).
// The launcher publishes theme.css at runtime; on the web we write a static one from design/tokens.
//   bun scripts/build-samples-site.ts && bunx wrangler deploy
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const out = join(root, "build/samples-site");
const samples = join(root, "samples");
const runtime = join(root, "android/app/src/main/assets/deft-runtime/v1");
const SKIP = new Set(["hostile", "deft-bridge.js"]);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const name of readdirSync(samples)) {
  if (SKIP.has(name) || name.startsWith(".")) continue;
  const src = join(samples, name);
  if (!statSync(src).isDirectory()) continue;
  cpSync(src, join(out, name), {
    recursive: true,
    filter: (p) => !p.endsWith("/config.json") || !p.includes("stripe-checkout"),
  });
}
cpSync(runtime, join(out, "_deft/v1"), { recursive: true });

type Color = { components: [number, number, number]; alpha?: number };
const tokens = (name: string): Record<string, { $value?: Color }> =>
  JSON.parse(readFileSync(join(root, `design/tokens/appearance.${name}.json`), "utf8"));
const oklch = (c: Color) =>
  `oklch(${c.components[0]} ${c.components[1]} ${c.components[2]}${c.alpha !== undefined ? ` / ${c.alpha}` : ""})`;
const light = tokens("light");
const dark = tokens("dark");
const pair = (key: string) => `light-dark(${oklch(light[key].$value!)}, ${oklch(dark[key].$value!)})`;

const keys: [string, string][] = [
  ["bg", "bg"], ["bg-grouped", "bgGrouped"], ["bg-elevated", "bgElevated"],
  ["label", "label"], ["label-2", "label2"], ["label-3", "label3"], ["label-4", "label4"],
  ["fill", "fill"], ["fill-2", "fill2"], ["fill-3", "fill3"], ["fill-4", "fill4"],
  ["separator", "separator"], ["error", "error"], ["warning", "warning"], ["success", "success"], ["info", "info"],
];
const lines = [
  "--deft-appearance: auto;",
  "--deft-accent: #e8622c;", // Deft ember
  "--deft-on-accent: #14120f;",
  ...keys
    .filter(([, k]) => typeof light[k]?.$value === "object" && typeof dark[k]?.$value === "object")
    .map(([css, k]) => `--deft-${css}: ${pair(k)};`),
  "--deft-info: var(--deft-label-2);",
  "--deft-tier: full;",
  "--deft-material-bar: color-mix(in oklch, var(--deft-bg-elevated) 80%, transparent);",
  "--deft-material-blur: none;",
  "--deft-border: 1px;",
  "--deft-density: 1;",
  "--deft-radius-box: var(--deft-radius-lg);",
  "--deft-radius-field: var(--deft-radius-md);",
  "--deft-radius-selector: 999px;",
  "--deft-fg: var(--deft-label);",
  "--deft-surface: var(--deft-bg-grouped);",
  "--deft-muted: var(--deft-label-2);",
  "--deft-red: var(--deft-error);",
];
writeFileSync(
  join(out, "_deft/v1/theme.css"),
  `/* GENERATED by scripts/build-samples-site.ts for the web samples host. */\n@layer deft.theme {\n  :root, [data-theme] {\n    color-scheme: light dark;\n${lines.map((l) => `    ${l}`).join("\n")}\n  }\n  [data-theme="light"] { color-scheme: light; }\n  [data-theme="dark"] { color-scheme: dark; }\n}\n`,
);
console.log(`built ${out}`);
