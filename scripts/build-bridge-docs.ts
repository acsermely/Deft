#!/usr/bin/env bun
/**
 * Generates the JS bridge docs the on-device agent reads, from bridge-catalog.json.
 *
 *   bun scripts/build-bridge-docs.ts           rewrite
 *   bun scripts/build-bridge-docs.ts --check   exit 1 if stale (also run by scripts/check.ts)
 *
 * Generated: agent/skills/js-bridge.md (the index, <= 4 KB) and the block between
 * `<!-- generated:methods -->` markers at the top of each agent/skills/js-bridge/<group>.md.
 * Hand-written: everything else in the group files (arguments and behaviour).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const skills = join(root, "android/app/src/main/assets/agent/skills");
const catalog = JSON.parse(readFileSync(join(root, "android/app/src/main/assets/agent/bridge-catalog.json"), "utf8")).capabilities as Record<
  string,
  { risk: string; methods: string[]; events: string[]; summary: string }
>;

export const GROUPS: { file: string; what: string; caps: string[] }[] = [
  { file: "people", what: "contacts, SMS, calls, call log", caps: ["contacts.read", "contacts.write", "sms.read", "sms.write", "sms.send", "calls.place", "calls.block", "calls.control", "telephony.ussd", "calllog.read", "calllog.write"] },
  { file: "storage", what: "phone files, photos, video, audio", caps: ["files.pick", "files.read", "files.write", "media.read"] },
  { file: "calendar-alerts", what: "calendar, reminders, notifications, tiles, widgets", caps: ["calendar.read", "calendar.write", "alarms", "notifications.post", "tiles", "widgets"] },
  { file: "intents", what: "open links, start other apps, receive shares", caps: ["intents.open", "intents.start", "share.receive"] },
  { file: "device", what: "sensors, GPS, camera, mic, screen, torch, volume, speech, keystore, clipboard", caps: ["location", "camera", "microphone", "haptics", "sensors", "system.stats", "display", "torch", "pip", "audio.control", "dnd", "keystore", "speech.tts", "speech.recognize", "clipboard.read", "clipboard.watch", "device.id", "media.drm", "midi", "payments.request"] },
  { file: "connectivity", what: "NFC, USB, Bluetooth, Wi-Fi, local network, internet", caps: ["nfc.read", "nfc.write", "nfc.tech", "nfc.hce", "nfc.hce.payment", "usb", "bluetooth.serial", "bluetooth.ble.central", "bluetooth.ble.peripheral", "net.local", "wifi.scan", "wifi.control", "net.sockets", "network.open", "network.user"] },
  { file: "system", what: "installed apps, usage stats, accounts, sign-in, push", caps: ["apps.list", "apps.launch", "usage.read", "accounts.own", "accounts.read", "auth.session", "push"] },
  { file: "special", what: "notification listener, accessibility, default roles, device admin, call screening", caps: ["notifications.listen", "accessibility", "role.browser", "role.assistant", "device.admin", "calls.screen"] },
  { file: "background", what: "background runs, keep running, media controls, wallpaper, keyboard", caps: ["background", "foreground", "media.session", "location.background", "wallpaper", "ime"] },
  { file: "basics", what: "errors, events, raw bridge, web APIs that are not bridge calls", caps: ["wasm", "storage.large", "web.embed"] },
];

function methodsLine(id: string): string {
  const c = catalog[id];
  const parts = [c.methods.length ? c.methods.map((m) => `\`${m}\``).join(", ") : "no bridge method"];
  if (c.events.length) parts.push(`events ${c.events.map((e) => `\`${e}\``).join(", ")}`);
  return `- \`${id}\` (${c.risk}): ${c.summary}. ${parts.join("; ")}`;
}

export function groupBlock(caps: string[]): string {
  return caps.map(methodsLine).join("\n");
}

export function indexDoc(): string {
  const rows = GROUPS.filter((g) => g.file !== "basics")
    .map((g) => `- \`js-bridge/${g.file}\` (${g.what}): ${g.caps.map((c) => `\`${c}\``).join(" ")}`)
    .join("\n");
  const noMethod = GROUPS.find((g) => g.file === "basics")!.caps.map((c) => `\`${c}\``).join(" ");
  return `# Deft JS bridge: index

GENERATED by scripts/build-bridge-docs.ts from bridge-catalog.json. Do not edit.

Any question about what the phone can do (features, sensors, data) or any phone call from app code: read this index first, never answer from memory. Find the capability below, then read ONLY that one file: \`skill.read name=js-bridge/<file>\` (exact path, no .md). Errors, events and \`has()\`: \`skill.read name=js-bridge/basics\`.

\`\`\`js
import { ready, call, on, has } from '/_deft/v1/bridge.js';
await ready();
const rows = await call('contacts.list', { limit: 50 });
\`\`\`

## Manifest

Declare each capability the app calls, with a plain-language \`reason\` of 10-140 characters (apps.verify fails otherwise). Ids only from this index. Tracking steps and light:

\`\`\`json
"capabilities": [ { "id": "sensors", "reason": "Show your step count and the light level" } ]
\`\`\`

No phone features: \`"capabilities": []\`. Manifest-only ids with no methods: ${noMethod}.

\`net.fetch\` (HTTPS reads of a feed or API) needs no capability: list its origin in manifest \`network\` and the user allows it on the consent sheet. Declare \`network.user\` only for servers the user adds; \`network.open\` (any HTTPS origin, high risk) only when an app truly needs many origins.

## Capability to file

${rows}
`;
}

/** Replace the generated block of a group file; returns null when the file or its markers are missing. */
export function groupDoc(file: string, current: string, caps: string[]): string | null {
  const open = "<!-- generated:methods -->";
  const close = "<!-- /generated -->";
  const a = current.indexOf(open);
  const b = current.indexOf(close);
  if (a < 0 || b < a || !caps.length) return null;
  return `${current.slice(0, a + open.length)}\n${groupBlock(caps)}\n${current.slice(b)}`;
}

export function outputs(): Record<string, string> {
  const known = new Set(Object.keys(catalog));
  const seen = new Set<string>();
  for (const g of GROUPS) for (const c of g.caps) {
    if (!known.has(c)) throw new Error(`group ${g.file}: unknown capability ${c}`);
    if (seen.has(c)) throw new Error(`capability ${c} in two groups`);
    seen.add(c);
  }
  const missing = [...known].filter((c) => !seen.has(c));
  if (missing.length) throw new Error(`capabilities in no group: ${missing.join(", ")}`);
  const out: Record<string, string> = { [join(skills, "js-bridge.md")]: indexDoc() };
  for (const g of GROUPS) {
    if (g.file === "basics") continue;
    const path = join(skills, "js-bridge", `${g.file}.md`);
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    const next = groupDoc(g.file, current, g.caps);
    if (next === null) throw new Error(`${path}: missing generated markers`);
    out[path] = next;
  }
  return out;
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [path, text] of Object.entries(outputs())) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === text) continue;
    if (check) {
      stale++;
      console.error(`stale: ${path.slice(root.length + 1)}`);
    } else {
      writeFileSync(path, text);
      console.log(`wrote ${path.slice(root.length + 1)}`);
    }
  }
  if (stale) process.exit(1);
}
