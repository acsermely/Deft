// Usage: bun tools/deft-design/icons.js [--check]
// Regenerates android/app/src/main/assets/deft-runtime/v1/icons.svg from ICONS (icon-list.js) and vendor/lucide/*.svg
// (Lucide, ISC, lucide-static 1.77.0). Add a name to icon-list.js and drop its SVG into vendor/lucide to extend the set.
// --check exits non-zero if the committed sprite is out of date.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { ICONS } from "./icon-list.js";
export { ICONS };

const LICENSE_LINE = "Lucide icons, ISC licence (see vendor/lucide/LICENSE). Generated by tools/deft-design/icons.js.";

/** The symbol body of one Lucide SVG: its viewBox and inner markup, comments and whitespace dropped. */
export function symbolOf(name, svg) {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1];
  if (!viewBox || inner === undefined) throw new Error(`not a Lucide svg: ${name}`);
  const body = inner.replace(/<!--[\s\S]*?-->/g, "").replace(/\s+/g, " ").replace(/>\s+</g, "><").trim();
  return { viewBox, body };
}

/** The sprite text for [names]. read(name) returns the Lucide svg source. Deterministic: same input, same bytes. */
export function buildSprite(names, read) {
  const seen = new Set();
  const symbols = names.map((name) => {
    if (seen.has(name)) throw new Error(`duplicate icon: ${name}`);
    seen.add(name);
    const { viewBox, body } = symbolOf(name, read(name));
    return `<symbol id="${name}" viewBox="${viewBox}" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" style="stroke-width:var(--deft-icon-stroke,1.5)">${body}</symbol>`;
  });
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- ${LICENSE_LINE} -->\n<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols.join("")}</svg>\n`;
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const vendor = join(dirname(fileURLToPath(import.meta.url)), "vendor/lucide");
const out = join(root, "android/app/src/main/assets/deft-runtime/v1/icons.svg");

if (import.meta.main) {
  const text = buildSprite(ICONS, (name) => readFileSync(join(vendor, `${name}.svg`), "utf8"));
  const current = existsSync(out) ? readFileSync(out, "utf8") : null;
  if (process.argv.includes("--check")) {
    if (current !== text) {
      console.error("stale: android/app/src/main/assets/deft-runtime/v1/icons.svg");
      process.exit(1);
    }
  } else if (current !== text) {
    writeFileSync(out, text);
    console.log(`wrote icons.svg (${ICONS.length} icons, ${text.length} bytes)`);
  }
}
