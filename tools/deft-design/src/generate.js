// Turns design/tokens/*.json into the three generated artefacts. Pure: no file writes here.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { num, oklchCss, oklchToArgb } from "./oklch.js";

export const OUTPUTS = {
  css: "android/app/src/main/assets/deft-runtime/v1/tokens.css",
  kotlin: "android/app/src/main/java/app/deft/ui/theme/Tokens.kt",
  docs: "docs/design/tokens.md",
};

const APPEARANCES = ["light", "dark"];
const HEADER_CSS = "/* GENERATED by tools/deft-design from design/tokens/*.json. Do not edit. Run: bun tools/deft-design/build.js */";
const HEADER_KT = "// GENERATED by tools/deft-design from design/tokens/*.json. Do not edit. Run: bun tools/deft-design/build.js";

export function loadTokens(root) {
  const read = (f) => JSON.parse(readFileSync(join(root, "design/tokens", f), "utf8"));
  const appearances = Object.fromEntries(APPEARANCES.map((name) => [name, read(`appearance.${name}.json`)]));
  return { style: read("style.json"), appearances };
}

/** Resolves a colour token node, following "{alias}" references within the same appearance. */
export function resolveColor(app, name, seen = []) {
  const node = app[name];
  if (!node) throw new Error(`unknown colour token "${name}"`);
  if (seen.includes(name)) throw new Error(`alias cycle at "${name}"`);
  const value = node.$value;
  if (typeof value === "string") {
    const m = /^\{(\w+)\}$/.exec(value);
    if (!m) throw new Error(`bad alias "${value}" in ${name}`);
    return resolveColor(app, m[1], [...seen, name]);
  }
  const [l, c, h] = value.components;
  return { l, c, h, alpha: value.alpha ?? 1 };
}

/** Spring samples for a damped spring (mass 1, stiffness = omega^2), N intervals across `duration` ms. */
export function springSamples({ dampingRatio: z, stiffness, duration }, intervals = 16) {
  const w = Math.sqrt(stiffness);
  const t_end = duration / 1000;
  const points = [];
  for (let i = 0; i <= intervals; i++) {
    const t = (i / intervals) * t_end;
    let y;
    if (z < 1) {
      const wd = w * Math.sqrt(1 - z * z);
      y = 1 - Math.exp(-z * w * t) * (Math.cos(wd * t) + ((z * w) / wd) * Math.sin(wd * t));
    } else if (z === 1) {
      y = 1 - (1 + w * t) * Math.exp(-w * t);
    } else {
      const k = Math.sqrt(z * z - 1);
      const r1 = w * (-z + k);
      const r2 = w * (-z - k);
      y = 1 - (r2 * Math.exp(r1 * t) - r1 * Math.exp(r2 * t)) / (r2 - r1);
    }
    points.push(i === intervals ? 1 : Math.round(y * 1000) / 1000);
  }
  return points;
}

export function springLinear(spec) {
  return `linear(${springSamples(spec).map((p) => num(p)).join(", ")})`;
}

const fmtPx = (n) => `${num(n)}px`;
const quoteFamilies = (list) => list.map((f, i) => (i === list.length - 1 && /^(system-ui|sans-serif|serif|monospace|ui-monospace)$/.test(f) ? f : `"${f}"`)).join(", ");
const cssFamilies = (list) => list.map((f) => (/^[a-z-]+$/.test(f) ? f : `"${f}"`)).join(", ");

function typeLines(name, step) {
  const kebab = name.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
  const v = step.$value;
  return [
    `    --deft-type-${kebab}-family: var(--deft-font-${v.family});`,
    `    --deft-type-${kebab}-size: ${fmtPx(v.size)};`,
    `    --deft-type-${kebab}-leading: ${fmtPx(v.leading)};`,
    `    --deft-type-${kebab}-weight: ${v.weight};`,
    `    --deft-type-${kebab}-tracking: ${fmtPx(v.tracking)};`,
  ].concat(v.uppercase ? [`    --deft-type-${kebab}-transform: uppercase;`] : []);
}

/** Served by LocalOriginPathHandler from /_deft/v1/fonts/ (revalidated per load; the WebView never caches intercepted responses across APK updates). */
export function fontFaceCss(faces) {
  return faces.flatMap((f) => [
    "@font-face {",
    `  font-family: "${f.family}";`,
    `  src: url("/_deft/v1/fonts/${f.file}") format("woff2");`,
    `  font-weight: ${f.weight};`,
    "  font-style: normal;",
    "  font-display: swap;",
    ...(f.unicodeRange ? [`  unicode-range: ${f.unicodeRange};`] : []),
    "}",
  ]);
}

export function cssFor(tokens) {
  const { style } = tokens;
  const lines = [];
  lines.push(HEADER_CSS, ...fontFaceCss(style.font.faces), "@layer deft.theme {", "  :root {");
  for (const k of ["text", "display", "mono", "numeric"]) lines.push(`    --deft-font-${k}: ${cssFamilies(style.font[k].$value)};`);
  lines.push("    --deft-font-ui: var(--deft-font-text);");
  lines.push(`    --deft-font-numeric-weight: ${style.font.numericWeight.$value};`);
  for (const [k, v] of Object.entries(style.radius)) lines.push(`    --deft-radius-${k}: ${v.$value};`);
  lines.push(`    --deft-radius-outer: var(--deft-radius-lg);`, `    --deft-pad: ${style.pad.$value};`);
  for (const [name, step] of Object.entries(style.type)) lines.push(...typeLines(name, step));
  for (const [name, spec] of Object.entries(style.motion.spring)) {
    lines.push(`    --deft-spring-${name}: ${springLinear(spec.$value)};`);
    lines.push(`    --deft-spring-${name}-duration: ${spec.$value.duration}ms;`);
  }
  const dot = style.motion.stepDot.$value;
  lines.push(`    --deft-step-dot: steps(${dot.steps}, ${dot.position});`);
  const m = style.material;
  const mix = (pct) => `color-mix(in oklch, var(--deft-bg-elevated) ${pct}%, transparent)`;
  lines.push(
    `    --deft-material-bar: ${mix(m.barAlpha.$value)};`,
    `    --deft-material-bar-reduced: ${mix(m.barAlphaReduced.$value)};`,
    `    --deft-material-blur: blur(${m.blur.$value}) saturate(${num(m.blurSaturate.$value)});`,
    `    --deft-material-rim: inset 0 0 0 .5px oklch(1 0 0 / ${num(m.rimAlpha.$value)}), inset 0 1px 0 oklch(1 0 0 / ${num(m.rimTopAlpha.$value)});`,
    `    --deft-icon-stroke: ${num(style.icon.stroke.$value)};`,
    `    --deft-hairline: ${style.separator.hairline.$value};`,
    "  }",
    "  /* Concentric helper: each element computes its own inner radius from its own outer radius and pad. */",
    "  * { --deft-radius-inner: calc(var(--deft-radius-outer) - var(--deft-pad)); }",
    "}",
  );
  // Type classes (proposal 3.4): one class per step, size, weight, leading and tracking set together.
  lines.push("@layer deft.components {");
  for (const [name, step] of Object.entries(style.type)) lines.push(typeClassLine(name, step));
  lines.push("}");
  return lines.join("\n") + "\n";
}

function typeClassLine(name, step) {
  const kebab = name.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
  const t = (p) => `var(--deft-type-${kebab}-${p})`;
  const upper = step.$value.uppercase ? " text-transform: uppercase;" : "";
  return `  .deft-${name} { font-family: ${t("family")}; font-size: ${t("size")}; line-height: ${t("leading")}; font-weight: ${t("weight")}; letter-spacing: ${t("tracking")};${upper} }`;
}

const ktNum = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const ktF = (n) => `${ktNum(n)}f`;
const ktLong = (argb) => `0x${argb.toString(16).toUpperCase().padStart(8, "0")}L`;

function neutralsFor(tokens, name) {
  const app = tokens.appearances[name];
  const argb = (t) => {
    const c = resolveColor(app, t);
    return oklchToArgb(c.l, c.c, c.h, c.alpha);
  };
  const oklch = (t) => {
    const c = resolveColor(app, t);
    return `Oklch(${ktNum(c.l)}, ${ktNum(c.c)}, ${ktNum(c.h)})`;
  };
  return {
    bg: argb("bg"), bgGrouped: argb("bgGrouped"), bgElevated: argb("bgElevated"),
    label: argb("label"), label2: argb("label2"), label3: argb("label3"), label4: argb("label4"),
    fill: argb("fill"), fill2: argb("fill2"), fill3: argb("fill3"), fill4: argb("fill4"),
    separator: argb("separator"),
    error: oklch("error"), warning: oklch("warning"), success: oklch("success"),
    info: argb("info"),
  };
}

export function kotlinFor(tokens) {
  const { style } = tokens;
  const out = [];
  const radius = Object.entries(style.radius).map(([k, v]) => `    val radius${k[0].toUpperCase()}${k.slice(1)}: Float = ${ktF(parseFloat(v.$value))}`);
  const type = Object.entries(style.type).map(([name, step]) => {
    const v = step.$value;
    return `    val ${name}: TypeStep = TypeStep(${ktF(v.size)}, ${ktF(v.leading)}, ${v.weight}, ${ktF(v.tracking)})`;
  });
  const spring = Object.entries(style.motion.spring).map(([name, s]) => {
    const v = s.$value;
    return `    val spring${name[0].toUpperCase()}${name.slice(1)}: SpringSpec = SpringSpec(${ktF(v.dampingRatio)}, ${ktF(v.stiffness)}, ${v.duration})`;
  });
  const m = style.material;
  const fam = (list) => `listOf(${list.map((f) => JSON.stringify(f)).join(", ")})`;
  out.push(
    HEADER_KT,
    "package app.deft.ui.theme",
    "",
    "data class TypeStep(val sizeSp: Float, val leadingSp: Float, val weight: Int, val trackingSp: Float)",
    "",
    "data class SpringSpec(val dampingRatio: Float, val stiffness: Float, val durationMs: Int)",
    "",
    "/** Neutral and status colours for one appearance. Colours are ARGB longs; status colours are OKLCH. */",
    "data class Neutrals(",
    "    val bg: Long, val bgGrouped: Long, val bgElevated: Long,",
    "    val label: Long, val label2: Long, val label3: Long, val label4: Long,",
    "    val fill: Long, val fill2: Long, val fill3: Long, val fill4: Long,",
    "    val separator: Long,",
    "    val error: Oklch, val warning: Oklch, val success: Oklch, val info: Long,",
    ")",
    "",
    "object DeftTokens {",
    `    const val DEFAULT_ACCENT = ${JSON.stringify(oklchCss({ l: style.accent.default.$value.components[0], c: style.accent.default.$value.components[1], h: style.accent.default.$value.components[2] }))}`,
    `    val defaultAccent: Oklch = Oklch(${style.accent.default.$value.components.map((n) => (Number.isInteger(n) ? n.toFixed(1) : String(n))).join(", ")})`,
    "",
    "    // Radii (dp)",
    ...radius,
    `    val padDp: Float = ${ktF(parseFloat(style.pad.$value))}`,
    "",
    "    // Type scale (sp). Tracking is in sp, which matches px on the launcher.",
    ...type,
    "",
    "    // Springs: damping ratio and stiffness (omega^2, mass 1), plus the CSS duration",
    ...spring,
    `    const val STEP_DOT_STEPS: Int = ${style.motion.stepDot.$value.steps}`,
    "",
    "    // Materials, icons and separators",
    `    val blurDp: Float = ${ktF(parseFloat(m.blur.$value))}`,
    `    val blurSaturate: Float = ${ktF(m.blurSaturate.$value)}`,
    `    val barAlpha: Float = ${ktF(m.barAlpha.$value / 100)}`,
    `    val barAlphaReduced: Float = ${ktF(m.barAlphaReduced.$value / 100)}`,
    `    val rimAlpha: Float = ${ktF(m.rimAlpha.$value)}`,
    `    val rimTopAlpha: Float = ${ktF(m.rimTopAlpha.$value)}`,
    `    val iconStroke: Float = ${ktF(style.icon.stroke.$value)}`,
    `    val hairlineDp: Float = ${ktF(parseFloat(style.separator.hairline.$value))}`,
    "",
    "    // Font families (bundled in a later phase; system fallbacks until then)",
    `    val fontText: List<String> = ${fam(style.font.text.$value)}`,
    `    val fontDisplay: List<String> = ${fam(style.font.display.$value)}`,
    `    val fontMono: List<String> = ${fam(style.font.mono.$value)}`,
    `    val fontNumeric: List<String> = ${fam(style.font.numeric.$value)}`,
    "",
  );
  for (const name of APPEARANCES) {
    const n = neutralsFor(tokens, name);
    const cap = name[0].toUpperCase() + name.slice(1);
    out.push(
      `    /** ${cap} appearance. */`,
      `    val appearance${cap}: Neutrals = Neutrals(`,
      `        bg = ${ktLong(n.bg)}, bgGrouped = ${ktLong(n.bgGrouped)}, bgElevated = ${ktLong(n.bgElevated)},`,
      `        label = ${ktLong(n.label)}, label2 = ${ktLong(n.label2)}, label3 = ${ktLong(n.label3)}, label4 = ${ktLong(n.label4)},`,
      `        fill = ${ktLong(n.fill)}, fill2 = ${ktLong(n.fill2)}, fill3 = ${ktLong(n.fill3)}, fill4 = ${ktLong(n.fill4)},`,
      `        separator = ${ktLong(n.separator)},`,
      `        error = ${n.error}, warning = ${n.warning}, success = ${n.success},`,
      `        info = ${ktLong(n.info)},`,
      "    )",
      "",
    );
  }
  out.push(
    "    fun appearance(name: String): Neutrals = when (name) {",
    "        \"light\" -> appearanceLight",
    "        else -> appearanceDark",
    "    }",
    "}",
  );
  return out.join("\n") + "\n";
}

/** Appearance token name to the CSS custom property name in theme.css (label2 -> label-2). */
export function cssName(n) {
  return n.replace(/([a-z])(\d)$/, "$1-$2").replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
}

export function docsFor(tokens, root) {
  const { style } = tokens;
  const rows = [];
  const row = (...cells) => rows.push(`| ${cells.join(" | ")} |`);
  const out = [];
  out.push(
    "# Design tokens",
    "",
    "<!-- GENERATED by tools/deft-design from design/tokens/*.json. Do not edit. Run: bun tools/deft-design/build.js -->",
    "",
    "Source: `design/tokens/style.json` (one style) and `design/tokens/appearance.{light,dark}.json`.",
    "Emitted to `deft-runtime/v1/tokens.css` (static), `ui/theme/Tokens.kt` (Compose), and the launcher's `theme.css` (accent and appearance, from `Palette.kt`).",
    "",
    "## Radii and spacing",
    "",
    "| Token | Value |",
    "| --- | --- |",
  );
  for (const [k, v] of Object.entries(style.radius)) row(`\`--deft-radius-${k}\``, v.$value);
  row("`--deft-radius-inner`", "`calc(var(--deft-radius-outer) - var(--deft-pad))`, computed per element");
  row("`--deft-pad`", style.pad.$value);
  out.push(...rows.splice(0), "");
  // Spacing and the tap size live in base.css (fluid clamp() values), not in design/tokens.
  const base = readFileSync(join(root, "android/app/src/main/assets/deft-runtime/v1/base.css"), "utf8");
  out.push("## Space and tap size", "", "Fluid steps from `base.css`. Use them for gaps and padding in `app.css`; never raw `px` or `rem`.", "", "| Token | Value |", "| --- | --- |");
  for (const m of base.matchAll(/--deft-(space-[a-z0-9]+|tap):\s*([^;]+);/g)) out.push(`| \`--deft-${m[1]}\` | ${m[2].replace(/\|/g, "\\|")} |`);
  out.push("");
  out.push("## Type scale", "", "| Step | Family | Size / leading | Weight | Tracking | Notes |", "| --- | --- | --- | --- | --- | --- |");
  for (const [name, step] of Object.entries(style.type)) {
    const v = step.$value;
    const kebab = name.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);
    out.push(`| \`--deft-type-${kebab}-*\` | ${v.family} | ${v.size}px / ${v.leading}px | ${v.weight} | ${v.tracking}px | ${v.uppercase ? "uppercase, micro-labels only" : ""} |`);
  }
  out.push("", "## Motion", "", "| Token | Value |", "| --- | --- |");
  for (const [name, spec] of Object.entries(style.motion.spring)) {
    const v = spec.$value;
    out.push(`| \`--deft-spring-${name}\` | damping ${v.dampingRatio}, stiffness ${v.stiffness}, ${v.duration}ms, emitted as \`linear()\` |`);
  }
  out.push(`| \`--deft-step-dot\` | steps(${style.motion.stepDot.$value.steps}, ${style.motion.stepDot.$value.position}), numbers and dot reveals only |`);
  out.push("", "## Material, icons, separators", "", "| Token | Value |", "| --- | --- |");
  const m = style.material;
  out.push(`| \`--deft-material-bar\` | color-mix(bg-elevated ${m.barAlpha.$value}%), reduced ${m.barAlphaReduced.$value}% |`);
  out.push(`| \`--deft-material-blur\` | blur(${m.blur.$value}) saturate(${num(m.blurSaturate.$value)}) |`);
  out.push(`| \`--deft-material-rim\` | inset hairline rim, alpha ${num(m.rimAlpha.$value)} / ${num(m.rimTopAlpha.$value)} |`);
  out.push(`| \`--deft-icon-stroke\` | ${num(style.icon.stroke.$value)} |`);
  out.push(`| \`--deft-hairline\` | ${style.separator.hairline.$value} |`);
  out.push("", "## Fonts", "", "| Token | Stack |", "| --- | --- |");
  for (const k of ["text", "display", "mono", "numeric"]) out.push(`| \`--deft-font-${k}\` | ${style.font[k].$value.join(", ")} |`);
  out.push(`| \`--deft-font-numeric-weight\` | ${style.font.numericWeight.$value} (Doto digits: deft-number, tile values, stepper) |`);
  out.push("", "## Appearance colours", "", "Each appearance is resolved in Kotlin with the accent. `theme.css` emits `light-dark()` pairs for auto.", "");
  out.push("| Token | light | dark |", "| --- | --- | --- |");
  const names = Object.keys(tokens.appearances.light).filter((k) => !k.startsWith("$"));
  const fmt = (c) => (c.alpha === 1 ? "" : ` / ${num(c.alpha)}`) + "";
  for (const n of names) {
    const cells = APPEARANCES.map((a) => {
      const app = tokens.appearances[a];
      const v = app[n].$value;
      if (typeof v === "string") return v;
      const c = resolveColor(app, n);
      return `${oklchCss(c)}`;
    });
    out.push(`| \`--deft-${cssName(n)}\` | ${cells.join(" | ")} |`);
  }
  out.push("", "Status colours are shifted away from the accent hue at runtime (Palette.kt). `info` is an alias of `label2`.", "");
  return out.join("\n");
}

export function generate(root) {
  const tokens = loadTokens(root);
  return {
    [OUTPUTS.css]: cssFor(tokens),
    [OUTPUTS.kotlin]: kotlinFor(tokens),
    [OUTPUTS.docs]: docsFor(tokens, root),
  };
}
