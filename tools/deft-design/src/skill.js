// The deft-design skill folder: one source (skill/deft-design) copied to the APK assets for skill.read,
// with references/tokens.md regenerated from the same tokens as tokens.css and Tokens.kt.
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { ICONS } from "../icons.js";

export const SKILL_DIR = "skill/deft-design";
export const SKILL_ASSETS = "android/app/src/main/assets/agent/skills/deft-design";

/** Every file under dir, as { "relative/path": text }. */
export function readTree(dir) {
  const out = {};
  if (!existsSync(dir)) return out;
  const walk = (d) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else out[relative(dir, p).split(sep).join("/")] = readFileSync(p, "utf8");
    }
  };
  walk(dir);
  return out;
}

/** Output map for the skill: the source tree, tokens.md generated, and the APK copy of both. */
export function skillOutputs(root, tokensDoc) {
  const tree = readTree(join(root, SKILL_DIR));
  tree["references/tokens.md"] = tokensDoc;
  tree["references/icons.md"] = iconsDoc();
  const out = {};
  for (const [rel, text] of Object.entries(tree)) {
    out[`${SKILL_DIR}/${rel}`] = text;
    out[`${SKILL_ASSETS}/${rel}`] = text;
  }
  return out;
}

/** Files in the APK skill folder that no longer have a source (removed or renamed). */
export function staleAssets(root, outputs) {
  return Object.keys(readTree(join(root, SKILL_ASSETS)))
    .map((rel) => `${SKILL_ASSETS}/${rel}`)
    .filter((rel) => !(rel in outputs));
}

/** references/icons.md: every sprite name, generated from tools/deft-design/icons.js. */
export function iconsDoc() {
  return [
    "# Icons",
    "",
    "<!-- GENERATED by tools/deft-design from tools/deft-design/icons.js. Do not edit. Run: bun tools/deft-design/build.js -->",
    "",
    `${ICONS.length} Lucide icons in the sprite. Use \`<deft-icon name="chevron-right" aria-hidden="true"></deft-icon>\`. A name not listed here draws nothing; lint warns FL632 and names the closest matches. Give an icon-only button an \`aria-label\`.`,
    "",
    ICONS.map((n) => `\`${n}\``).join(", "),
    "",
  ].join("\n");
}
